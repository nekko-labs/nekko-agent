/**
 * Accent colors a preset used to ship. Choosing a preset saves its accents into
 * settings, so a retuned preset would otherwise never reach anyone who picked
 * it before. A saved value equal to a retired one is read as the current one;
 * any other value is the user's own choice and is left alone.
 */
const RETIRED_PRESET_ACCENTS: Record<string, Record<string, string>> = {
  nebula: { '#a78bfa': '#9d8ce6', '#f472b6': '#d98bb6' },
  terminal: { '#22c55e': '#3fb96a', '#84cc16': '#8fbf3a' },
};

/** A saved accent, upgraded if it is a color the preset no longer ships. */
export function currentPresetAccent(presetId: string | undefined, saved: string): string;
export function currentPresetAccent(presetId: string | undefined, saved: string | undefined): string | undefined;
export function currentPresetAccent(presetId: string | undefined, saved: string | undefined): string | undefined {
  if (!presetId || !saved) return saved;
  return RETIRED_PRESET_ACCENTS[presetId]?.[saved.toLowerCase()] ?? saved;
}

/** Experimental presets grouped into their families, in catalog order. */
export function experimentalFamilies(): Array<{ id: string; label: string; presets: ThemePreset[] }> {
  const out: Array<{ id: string; label: string; presets: ThemePreset[] }> = [];
  for (const p of THEME_PRESETS) {
    if (p.group !== 'experimental' || !p.family) continue;
    let f = out.find((x) => x.id === p.family);
    if (!f) out.push((f = { id: p.family, label: p.familyLabel ?? p.family, presets: [] }));
    f.presets.push(p);
  }
  return out;
}

/**
 * The preset whose colours actually apply. System follows the computer's
 * light/dark mode with the branded looks, Nekko Dark or Lilac; every other id
 * is itself.
 */
export function resolveThemePreset(presetId: string | undefined, prefersDark: boolean): string | undefined {
  if (presetId !== 'system') return presetId;
  return prefersDark ? 'nekko-dark' : 'lilac';
}

/**
 * The preset the user picked. Nothing saved (a fresh profile) is System; a base
 * mode saved without a preset stays without one.
 */
export function themePresetOf(settings: { theme?: string; themePreset?: string } | null | undefined): string | undefined {
  if (settings?.themePreset) return settings.themePreset;
  return !settings?.theme || settings.theme === 'system' ? 'system' : undefined;
}

/** Look up a preset by id. */
export function findThemePreset(id: string | undefined): ThemePreset | undefined {
  return THEME_PRESETS.find((p) => p.id === id);
}

