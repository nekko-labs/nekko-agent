//! Making `nekko-agent` work in a terminal as a consequence of installing the
//! app: a port of `apps/desktop/src/main/cli-install.ts`.
//!
//! 1. The CLI is bundled as CommonJS (apps/cli/scripts/bundle-app.mjs) and
//!    run by the app's own Electron binary with `ELECTRON_RUN_AS_NODE=1`, so
//!    no Node, no npm and no network are involved.
//! 2. A tiny launcher (a `.cmd` on Windows, a `sh` script elsewhere) is
//!    written into `<userData>/bin`, and that directory is put on PATH: the
//!    user's own `Path` on Windows, a marked line in the shell profiles on
//!    macOS/Linux.
//! 3. The address and token go to `cli-link.json` (`write_cli_link`), which
//!    the CLI reads when no flag or env var says otherwise.
//!
//! Everything here is best-effort and reversible; a failure is reported in
//! the Server tab with the manual fallback (the npm package) still true.

use serde_json::{Value, json};
use std::path::{Path, PathBuf};

/// Marker so the profile line can be recognised and not written twice.
const PROFILE_MARKER: &str = "# Added by Nekko Agent (nekko-agent CLI)";
const NO_CLI: &str = "This build does not include the CLI. Install it from npm instead: npm install -g nekko-agent";
/// `CLI_LINK_FILE` (packages/shared/src/cli-link.ts).
pub const CLI_LINK_FILE: &str = "cli-link.json";

/// What the installer needs to know about the app.
#[derive(Clone, Debug, Default)]
pub struct AppPaths {
    pub is_packaged: bool,
    /// The Electron binary the launcher runs (`process.execPath`).
    pub exe: String,
    /// `process.resourcesPath`, where a packaged build keeps `cli/`.
    pub resources: Option<String>,
    /// `app.getAppPath()`, for a development checkout's CLI build.
    pub app_path: Option<String>,
    /// `app.getPath('userData')`.
    pub user_data: String,
}

fn resolve(parts: &[&str]) -> String {
    if cfg!(windows) { nekko_tools::path::win32::resolve(parts) } else { nekko_tools::path::posix::resolve(parts) }
}

fn join(dir: &str, name: &str) -> String {
    resolve(&[dir, name])
}

/// Where the bundled CLI ends up, packaged and in development.
fn bundled_cli_path(app: &AppPaths) -> Option<String> {
    let candidates: Vec<String> = if app.is_packaged {
        app.resources.iter().map(|r| resolve(&[r, "cli", "nekko-agent-cli.cjs"])).collect()
    } else {
        app.app_path
            .iter()
            .flat_map(|a| {
                [
                    resolve(&[a, "../../apps/cli/app-dist/nekko-agent-cli.cjs"]),
                    resolve(&[a, "../cli/app-dist/nekko-agent-cli.cjs"]),
                ]
            })
            .collect()
    };
    candidates.into_iter().find(|p| Path::new(p).exists())
}

/// The app's Electron binary and its bundled CLI, to run the CLI as Node
/// (the Claude Agent approval bridge, harness.rs).
pub fn bundled_cli(native: &crate::config::NativeConfig) -> Option<(String, String)> {
    let app = AppPaths {
        is_packaged: native.is_packaged,
        exe: native.exe_path.clone(),
        resources: native.resources_path.clone(),
        app_path: native.app_path.clone(),
        user_data: String::new(),
    };
    if app.exe.is_empty() {
        return None;
    }
    bundled_cli_path(&app).map(|cli| (app.exe.clone(), cli))
}

/// The directory the launcher goes in: `<userData>/bin`.
pub fn cli_bin_dir(user_data: &str) -> String {
    join(user_data, "bin")
}

/// The launcher's own path, named as the platform expects to find it.
pub fn cli_bin_path(user_data: &str) -> String {
    join(&cli_bin_dir(user_data), if cfg!(windows) { "nekko-agent.cmd" } else { "nekko-agent" })
}

/// The launcher's contents: run the app's Electron as plain Node on the
/// bundled CLI, passing the user's arguments through.
pub fn launcher_script(windows: bool, electron: &str, cli: &str) -> String {
    if windows {
        return [
            "@echo off",
            "rem Nekko Agent CLI launcher. Regenerated by the app; edits will be lost.",
            "setlocal",
            "set ELECTRON_RUN_AS_NODE=1",
            &format!("\"{electron}\" \"{cli}\" %*"),
            "endlocal",
            "",
        ]
        .join("\r\n");
    }
    [
        "#!/bin/sh",
        "# Nekko Agent CLI launcher. Regenerated by the app; edits will be lost.",
        &format!("ELECTRON_RUN_AS_NODE=1 exec \"{electron}\" \"{cli}\" \"$@\""),
        "",
    ]
    .join("\n")
}

/// `trimTrailingSlashes(s, true)`.
fn trim_slashes(s: &str) -> &str {
    s.trim_end_matches(['/', '\\'])
}

/// Whether a directory is on a PATH value (`;`-separated on Windows).
pub fn dir_on_path(dir: &str, path_value: &str, windows: bool) -> bool {
    let wanted = trim_slashes(dir).to_lowercase();
    path_value.split(if windows { ';' } else { ':' }).any(|e| trim_slashes(e).to_lowercase() == wanted)
}

fn path_now() -> String {
    std::env::var("PATH").unwrap_or_default()
}

/// Put the bin dir on PATH for future shells: `(changed, message)`.
fn persist_path(bin_dir: &str) -> (bool, Option<String>) {
    if cfg!(windows) {
        if dir_on_path(bin_dir, &path_now(), true) {
            return (false, None);
        }
        // The *user* Path only, read from the user's own environment: this
        // process's PATH is the system and user entries merged, and setx
        // truncates at 1024 characters. The folder travels as an env var so
        // no quoting of a path is involved.
        let script = [
            "$dir = $env:NEKKO_BIN_DIR",
            "$cur = [Environment]::GetEnvironmentVariable('Path', 'User')",
            "$parts = @(); if ($cur) { $parts = $cur -split ';' | Where-Object { $_ } }",
            "if ($parts | Where-Object { $_.TrimEnd('\\') -ieq $dir.TrimEnd('\\') }) { 'present'; exit 0 }",
            "[Environment]::SetEnvironmentVariable('Path', (($parts + $dir) -join ';'), 'User')",
            "'added'",
        ]
        .join("; ");
        let mut cmd = std::process::Command::new("powershell.exe");
        cmd.args(["-NoProfile", "-NonInteractive", "-Command", &script])
            .env("NEKKO_BIN_DIR", bin_dir)
            .stdin(std::process::Stdio::null())
            .stderr(std::process::Stdio::null());
        #[cfg(windows)]
        {
            use std::os::windows::process::CommandExt;
            cmd.creation_flags(0x0800_0000);
        }
        return match run_with_timeout(cmd, std::time::Duration::from_secs(15)) {
            Some(out) => (out.trim() == "added", None),
            None => (false, Some("Could not update your PATH. Add the folder above to it by hand.".into())),
        };
    }

    let Some(home) = std::env::var("HOME").ok().filter(|h| !h.is_empty()) else {
        return (false, Some("No home directory to add a PATH line to.".into()));
    };
    let line = format!("{PROFILE_MARKER}\nexport PATH=\"{bin_dir}:$PATH\"\n");
    let mut changed = false;
    for name in [".zshrc", ".bashrc", ".profile"] {
        let file = Path::new(&home).join(name);
        if !file.exists() {
            continue;
        }
        // Someone else's file; a failure here is not fatal.
        let Ok(body) = std::fs::read_to_string(&file) else { continue };
        if body.contains(PROFILE_MARKER) {
            continue;
        }
        if std::fs::write(&file, format!("{}\n\n{line}", body.trim_end_matches(js_space))).is_ok() {
            changed = true;
        }
    }
    let home = Path::new(&home);
    if !changed && !home.join(".zshrc").exists() && !home.join(".bashrc").exists() {
        use std::io::Write;
        let appended = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(home.join(".profile"))
            .and_then(|mut f| f.write_all(line.as_bytes()));
        if appended.is_err() {
            return (false, Some("Could not write a shell profile. Add the folder above to your PATH.".into()));
        }
        changed = true;
    }
    (changed, None)
}

/// JavaScript's `\s`, for `replace(/\s*$/, '')`.
fn js_space(c: char) -> bool {
    c.is_whitespace() || c == '\u{feff}'
}

/// A successful run's stdout, or `None` on a failure or a timeout (`execFileSync`'s throw).
fn run_with_timeout(mut cmd: std::process::Command, limit: std::time::Duration) -> Option<String> {
    let mut child = cmd.stdout(std::process::Stdio::piped()).spawn().ok()?;
    let started = std::time::Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                let mut out = String::new();
                if let Some(mut s) = child.stdout.take() {
                    let _ = std::io::Read::read_to_string(&mut s, &mut out);
                }
                return status.success().then_some(out);
            }
            Ok(None) if started.elapsed() < limit => std::thread::sleep(std::time::Duration::from_millis(50)),
            _ => {
                let _ = child.kill();
                let _ = child.wait();
                return None;
            }
        }
    }
}

fn status(
    installed: bool,
    on_path: bool,
    bin_path: Option<String>,
    bin_dir: String,
    command: String,
    message: Option<String>,
) -> Value {
    let mut out = serde_json::Map::new();
    out.insert("available".into(), json!(true));
    out.insert("installed".into(), json!(installed));
    out.insert("onPath".into(), json!(on_path));
    if let Some(p) = bin_path {
        out.insert("binPath".into(), json!(p));
    }
    out.insert("binDir".into(), json!(bin_dir));
    out.insert("command".into(), json!(command));
    if let Some(m) = message {
        out.insert("message".into(), json!(m));
    }
    Value::Object(out)
}

/// Write the launcher and make sure its directory is on PATH. Idempotent: the
/// launcher is rewritten every time (it names absolute paths that move when
/// the app updates) and PATH is only touched when it is actually missing.
pub fn install(app: &AppPaths) -> Value {
    let bin_dir = cli_bin_dir(&app.user_data);
    let bin_path = cli_bin_path(&app.user_data);
    let Some(cli) = bundled_cli_path(app) else {
        return status(false, false, None, bin_dir, "nekko-agent".into(), Some(NO_CLI.into()));
    };
    let written = std::fs::create_dir_all(&bin_dir)
        .and_then(|()| std::fs::write(&bin_path, launcher_script(cfg!(windows), &app.exe, &cli)))
        .and_then(|()| make_executable(&bin_path));
    if let Err(e) = written {
        return status(
            false,
            false,
            None,
            bin_dir,
            "nekko-agent".into(),
            Some(format!("Could not write the launcher: {e}")),
        );
    }
    let already = dir_on_path(&bin_dir, &path_now(), cfg!(windows));
    let (changed, message) = if already { (false, None) } else { persist_path(&bin_dir) };
    let mut out = status(
        true,
        already,
        Some(bin_path.clone()),
        bin_dir,
        // Until PATH takes effect, the full path is the command that actually works.
        if already { "nekko-agent".into() } else { bin_path },
        message,
    );
    out["needsRestart"] = json!(!already && changed);
    out
}

#[cfg(unix)]
fn make_executable(path: &str) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
}

#[cfg(not(unix))]
fn make_executable(_: &str) -> std::io::Result<()> {
    Ok(())
}

/// Report the state without writing anything (what the Server tab polls).
pub fn install_status(app: &AppPaths) -> Value {
    let bin_dir = cli_bin_dir(&app.user_data);
    let bin_path = cli_bin_path(&app.user_data);
    let installed = Path::new(&bin_path).exists();
    let on_path = dir_on_path(&bin_dir, &path_now(), cfg!(windows));
    let command = if installed && !on_path { bin_path.clone() } else { "nekko-agent".into() };
    let message = bundled_cli_path(app).is_none().then(|| NO_CLI.to_string());
    status(installed, on_path, installed.then_some(bin_path), bin_dir, command, message)
}

/// Where the CLI looks for the link file: `NEKKO_DATA_DIR`, else
/// `~/.nekko-agent` (`defaultUserDataDir`). Not the app's userData: the CLI
/// has no way to know where that is.
pub fn cli_link_dir() -> PathBuf {
    match std::env::var_os("NEKKO_DATA_DIR").filter(|d| !d.is_empty()) {
        Some(d) => PathBuf::from(d),
        None => nekko_js::home_dir().unwrap_or_default().join(".nekko-agent"),
    }
}

/// Write (or clear) the address and token the CLI should use by default, `0600`:
/// it carries a bearer token for an endpoint that can run shell commands.
pub fn write_cli_link(dir: &Path, link: &Value) {
    // The CLI falls back to the local data directory; not worth an error box.
    let _ = std::fs::create_dir_all(dir);
    let file = dir.join(CLI_LINK_FILE);
    let text = nekko_js::stringify_pretty(link, "  ");
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        let opened = std::fs::OpenOptions::new().write(true).create(true).truncate(true).mode(0o600).open(&file);
        if let Ok(mut f) = opened {
            let _ = std::io::Write::write_all(&mut f, text.as_bytes());
        }
        let _ = make_private(&file);
    }
    #[cfg(not(unix))]
    {
        let _ = std::fs::write(&file, text);
    }
}

#[cfg(unix)]
fn make_private(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launchers_match_the_ts() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/desktop-features.json");
        let g: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        for case in g["launchers"].as_array().unwrap() {
            let windows = case["platform"] == "win32";
            let script = launcher_script(windows, case["electron"].as_str().unwrap(), case["cli"].as_str().unwrap());
            assert_eq!(script, case["script"].as_str().unwrap(), "{}", case["platform"]);
        }
    }

    #[test]
    fn a_folder_is_found_on_path_however_it_is_written() {
        assert!(dir_on_path("C:\\Users\\a\\bin", "C:\\Windows;c:\\users\\A\\BIN\\;D:\\x", true));
        assert!(!dir_on_path("C:\\Users\\a\\bin", "C:\\Users\\a\\bin2;C:\\Users\\a", true));
        assert!(dir_on_path("/home/a/bin/", "/usr/bin:/home/a/bin", false));
        assert!(!dir_on_path("/home/a/bin", "/usr/bin;/home/a/bin", false));
        assert!(!dir_on_path("/x", "", false));
    }

    #[test]
    fn a_build_without_the_cli_says_so_and_writes_nothing() {
        let dir = std::env::temp_dir().join(format!("nekkod-cli-install-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let app = AppPaths { user_data: dir.to_string_lossy().into(), ..AppPaths::default() };
        let s = install(&app);
        assert_eq!(s["installed"], false);
        assert_eq!(s["message"], NO_CLI);
        assert_eq!(s["command"], "nekko-agent");
        assert!(!dir.join("bin").exists());
        let s = install_status(&app);
        assert_eq!(s["installed"], false);
        assert!(s.get("binPath").is_none());
        assert_eq!(s["binDir"], cli_bin_dir(&app.user_data));
    }

    #[test]
    fn the_launcher_names_the_app_and_the_bundled_cli() {
        let dir = std::env::temp_dir().join(format!("nekkod-cli-launcher-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let resources = dir.join("resources");
        std::fs::create_dir_all(resources.join("cli")).unwrap();
        std::fs::write(resources.join("cli/nekko-agent-cli.cjs"), "//").unwrap();
        let app = AppPaths {
            is_packaged: true,
            exe: "/opt/app/nekko".into(),
            resources: Some(resources.to_string_lossy().into()),
            app_path: None,
            user_data: dir.join("data").to_string_lossy().into(),
        };
        // Only the launcher: the PATH step is not run against this machine's PATH here.
        let bin = cli_bin_path(&app.user_data);
        std::fs::create_dir_all(cli_bin_dir(&app.user_data)).unwrap();
        let cli = bundled_cli_path(&app).unwrap();
        std::fs::write(&bin, launcher_script(cfg!(windows), &app.exe, &cli)).unwrap();
        let s = install_status(&app);
        assert_eq!(s["installed"], true);
        assert_eq!(s["binPath"], bin);
        assert!(s.get("message").is_none());
        assert!(std::fs::read_to_string(&bin).unwrap().contains("nekko-agent-cli.cjs"));
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn the_link_file_is_written_as_the_ts_wrote_it() {
        let dir = std::env::temp_dir().join(format!("nekkod-cli-link-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        write_cli_link(
            &dir,
            &json!({ "url": "http://127.0.0.1:1439", "token": "t", "enabled": true, "updatedAt": 5, "pid": 9 }),
        );
        let text = std::fs::read_to_string(dir.join(CLI_LINK_FILE)).unwrap();
        assert_eq!(
            text,
            "{\n  \"url\": \"http://127.0.0.1:1439\",\n  \"token\": \"t\",\n  \"enabled\": true,\n  \"updatedAt\": 5,\n  \"pid\": 9\n}"
        );
        let _ = std::fs::remove_dir_all(dir);
    }
}
