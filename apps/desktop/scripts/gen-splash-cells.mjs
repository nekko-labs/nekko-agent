// Regenerates src/renderer/splashCells.ts: the startup splash's pixel cat at
// its three resolutions. Rasterising the logo at launch took ~160ms of main
// thread (three canvases and getImageData) right as the window opened, so the
// cells are worked out here once instead. Run after changing the logo path:
//   node apps/desktop/scripts/gen-splash-cells.mjs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const require = createRequire(here('../../../package.json'));
const { chromium } = require('playwright-core');

const brand = readFileSync(here('../src/renderer/components/BrandMark.tsx'), 'utf8');
const head = brand.match(/BRAND_HEAD\s*=\s*'([^']+)'/)?.[1];
if (!head) throw new Error('BRAND_HEAD not found in BrandMark.tsx');

const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage();
const layers = await page.evaluate((PATH) => {
  // Cell size near `step` that puts both ear tips (9.351 either side of centre) on cell centres.
  const fit = (step) => 9.351 / (Math.round(9.351 / step - 0.5) + 0.5);
  // Cells whose centre falls inside the logo, grown a touch at coarse sizes so the line stays joined.
  const cells = (step) => {
    const grow = Math.max(0, step * 0.5 - 0.5), R = 40, x0 = 0, y0 = -0.5, w = 24, h = 19;
    const cv = document.createElement('canvas'); cv.width = w * R; cv.height = h * R;
    const ctx = cv.getContext('2d'); ctx.scale(R, R); ctx.translate(-x0, -y0);
    const p = new Path2D(PATH); ctx.fill(p, 'evenodd'); ctx.lineJoin = 'miter'; ctx.miterLimit = 12; ctx.lineWidth = 0.5 + 2 * grow; ctx.stroke(p);
    const img = ctx.getImageData(0, 0, cv.width, cv.height).data, out = [];
    const nx = Math.ceil(12 / step) + 1, ny = Math.ceil(10 / step) + 1, oy = 2.016 - step / 2;
    for (let j = -2; j < ny * 2; j++) for (let i = -nx; i < nx; i++) {
      const x = +(12 + i * step).toFixed(4), y = +(oy + j * step).toFixed(4);
      const px = Math.floor((x + step / 2 - x0) * R), py = Math.floor((y + step / 2 - y0) * R);
      if (px >= 0 && py >= 0 && px < cv.width && py < cv.height && img[(py * cv.width + px) * 4 + 3] > 127) out.push([+x.toFixed(3), +y.toFixed(3)]);
    }
    return out;
  };
  // One path per layer, each row of touching cells merged so anti-aliasing never shows seams.
  const rows = (list, s) => {
    const m = new Map(), e = 0.02, d = [];
    for (const [x, y] of list) { const k = y.toFixed(3); if (!m.has(k)) m.set(k, []); m.get(k).push(x); }
    for (const [k, xs] of m) {
      xs.sort((a, b) => a - b); let a = xs[0], prev = xs[0];
      for (const x of [...xs.slice(1), Infinity]) { if (x - prev > s * 1.5) { d.push(`M${a.toFixed(3)} ${(+k - e).toFixed(3)}h${(prev + s - a).toFixed(3)}v${(s + 2 * e).toFixed(3)}h${(-(prev + s - a)).toFixed(3)}Z`); a = x; } prev = x; }
    }
    return d.join('');
  };
  const [s1, s2, s3] = [1.5, 1, 0.5].map(fit);
  return { s1, chunky: cells(s1), mid: rows(cells(s2), s2), fine: rows(cells(s3), s3) };
}, head);
await browser.close();

writeFileSync(here('../src/renderer/splashCells.ts'), `// Generated by scripts/gen-splash-cells.mjs from BRAND_HEAD. Do not edit by hand.

/** Cell size of the chunky first beat, in logo units. */
export const CHUNKY_SIZE = ${+layers.s1.toFixed(4)};
/** Top-left corners of the chunky cells, popped in one by one. */
export const CHUNKY_CELLS: readonly (readonly [number, number])[] = ${JSON.stringify(layers.chunky)};
/** The medium and fine beats, each one path. */
export const MID_PATH = '${layers.mid}';
export const FINE_PATH = '${layers.fine}';
`);
// The iPhone app plays the same splash (apps/ios/App/Views/Splash.swift).
writeFileSync(here('../../ios/App/Views/SplashCells.swift'), swiftCells(head, layers));
console.log(`chunky ${layers.chunky.length} cells, mid ${layers.mid.length} chars, fine ${layers.fine.length} chars`);

function swiftCells(brandHead, l) {
  return `// Generated by apps/desktop/scripts/gen-splash-cells.mjs from BRAND_HEAD. Do not edit by hand.

enum SplashCells {
    static let brandHead = "${brandHead}"
    /// Cell size of the chunky first beat, in logo units.
    static let chunkySize = ${+l.s1.toFixed(4)}
    /// Top-left corners of the chunky cells, popped in one by one.
    static let chunkyCells: [(Double, Double)] = [${l.chunky.map(([x, y]) => `(${x}, ${y})`).join(', ')}]
    /// The medium and fine beats, each one path.
    static let midPath = "${l.mid}"
    static let finePath = "${l.fine}"
}
`;
}
