#!/usr/bin/env node
// Draws the desktop's computer icons (COMPUTER_ICON_GLYPHS) into the phones' assets:
// an SVG imageset per icon for the iPhone, a vector drawable per icon for Android.
// The desktop stays the only place the drawings live. Run it after changing one:
//   node scripts/computer-icons.mjs
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const iosDir = join(root, 'apps/ios/App/Assets.xcassets/ComputerIcons');
export const androidDir = join(root, 'apps/android/app/src/main/res/drawable');

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
const n = (v) => String(Number(v.toFixed(3)));

function attrs(s) {
  return Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
}

/**
 * Joined, a leading relative `m` would follow on from the shape before it, so it becomes `M`.
 * The pairs after its first stay relative lines, so they get an explicit `l`.
 */
function absoluteStart(d) {
  const m = d.match(/^m(-?[\d.]+)[ ,]*(-?[\d.]+)/);
  if (!m) return d;
  const rest = d.slice(m[0].length).trimStart();
  return `M${m[1]} ${m[2]}${/^[-\d.]/.test(rest) ? 'l' : ''}${rest}`;
}

/** One rect, circle or path as path data, since a vector drawable has only paths. */
function shapePath(tag, a) {
  if (tag === 'path') return absoluteStart(a.d);
  const v = (k) => Number(a[k] ?? 0);
  if (tag === 'circle') {
    const [cx, cy, r] = [v('cx'), v('cy'), v('r')];
    return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0Z`;
  }
  const [x, y, w, h, r] = [v('x'), v('y'), v('width'), v('height'), v('rx')];
  const arc = (dx, dy) => `a${n(r)} ${n(r)} 0 0 1 ${n(dx)} ${n(dy)}`;
  return `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}${arc(r, r)}v${n(h - 2 * r)}${arc(-r, r)}h${n(2 * r - w)}${arc(-r, -r)}v${n(2 * r - h)}${arc(r, -r)}Z`;
}

/** Every shape in a rendered glyph as one path's data. Refuses a shape it doesn't know, so none goes missing. */
export function pathData(svg) {
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const shapes = [...inner.matchAll(/<(\w+)\s([^>]*)><\/\1>/g)];
  if (shapes.map((m) => m[0]).join('') !== inner) throw new Error(`Unexpected markup in ${svg}`);
  return shapes.map((m) => {
    if (!['path', 'rect', 'circle'].includes(m[1])) throw new Error(`No conversion for <${m[1]}>`);
    return shapePath(m[1], attrs(m[2]));
  }).join('');
}

function drawable(svg) {
  const a = attrs(svg.match(/^<svg[^>]*>/)[0]);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/computer-icons.mjs from the desktop's COMPUTER_ICON_GLYPHS. Tinted where it is shown. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:pathData="${pathData(svg)}"
        android:strokeColor="#FF000000"
        android:strokeWidth="${a['stroke-width']}"
        android:strokeLineCap="${a['stroke-linecap']}"
        android:strokeLineJoin="${a['stroke-linejoin']}" />
</vector>
`;
}

/** Black, not currentColor: the asset catalog tints the shape by its alpha and has no current color. */
function standaloneSvg(svg) {
  return `${svg
    .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
    .replace('stroke="currentColor"', 'stroke="#000"')
    .replace('width="20"', 'width="24"')
    .replace('height="20"', 'height="24"')}\n`;
}

async function glyphs() {
  const { build } = createRequire(import.meta.url)('esbuild');
  const entry = `
    import { createElement } from 'react';
    import { renderToStaticMarkup } from 'react-dom/server';
    import { COMPUTER_ICON_GLYPHS } from './apps/desktop/src/renderer/icons.tsx';
    import { COMPUTER_ICONS } from './packages/shared/src/computers.ts';
    export const rendered = COMPUTER_ICONS.map((name) => [name, renderToStaticMarkup(createElement(COMPUTER_ICON_GLYPHS[name]))]);
  `;
  const out = await build({
    stdin: { contents: entry, resolveDir: root, loader: 'tsx' },
    bundle: true, write: false, format: 'cjs', platform: 'node', logLevel: 'error',
  });
  const mod = { exports: {} };
  new Function('module', 'exports', 'require', out.outputFiles[0].text)(mod, mod.exports, createRequire(import.meta.url));
  return mod.exports.rendered;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = await glyphs();
  rmSync(iosDir, { recursive: true, force: true });
  mkdirSync(iosDir, { recursive: true });
  writeFileSync(join(iosDir, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  for (const [name, svg] of rendered) {
    const set = join(iosDir, `computer-${name}.imageset`);
    mkdirSync(set);
    writeFileSync(join(set, `computer-${name}.svg`), standaloneSvg(svg));
    writeFileSync(join(set, 'Contents.json'), json({
      images: [{ filename: `computer-${name}.svg`, idiom: 'universal' }],
      info: { author: 'xcode', version: 1 },
      properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
    }));
    writeFileSync(join(androidDir, `computer_icon_${name}.xml`), drawable(svg));
  }
  console.log(`${rendered.length} icons written`);
}
